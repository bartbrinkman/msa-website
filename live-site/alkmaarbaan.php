			<h1>Alkmaarbaan</h1>
				
				<img src="images/Alkmaar-Stationsbord.jpg" /><br/>
				
				<p>De Alkmaarbaan is een gelijkstroombaan in de schaal H0 en geeft ongeveer de spoor situatie in en rond Alkmaar weer aan het begin van de jaren vijftig. 'Ongeveer', want wegens de vorm en afmetingen van onze clubruimte hebben we wat concessies moeten doen. Zo is bijvoorbeeld de bocht bij de Wochnumse buurt rechtgetrokken en zijn er een paar gebouwen verplaatst.</p>

				<p>Naast het station van Alkmaar en de oude draaibrug over het Noordhollands Kanaaal hebben we ook nog een plekje gevonden voor de hefbrug over kanaal Alkmaar - Kolhorn en de replica van het oude station van Heerhugowaard.</p>

				<p>De Alkmaarbaan is de oudste baan van de Modelspoorclub Alkmaar en is door de jaren heen een aantal keer verhuist. Een groot deel van de scenery heeft de verhuizing en de tijd redelijk overleeft maar, toch valt er nog wel het een en ander te renoveren. Omdat alle gebouwen zelf gebouwde schaalmodellen naar de werkelijkheid zijn vragen dit soort renovatiewerkzaamheden vaak veel tijd.</p>

				<h2>Besturing</h2>

				<p>De Alkmaarbaan was analoog en digitaal tegelijk. Het was mogelijk om met analoge en digitale treinen door elkaar heen te rijden. De hele baan is voorzien van een bloksysteem wat voorkomt dat treinen tegen elkaar kunnen botsen dat werd bestuurd door het systeem Koploper. Wij zijn echter overgestapt op iTrain en hebben daarbij besloten om alleen nog digitaal verder te rijden. Ons Dinamo systeem wat we dus eerst aan Koploper hadden gekoppeld werkt nu met iTrain.</p>

				<h2>Lopende projecten:</h2>

				<p>Op dit moment is er gestart met het vervangen van alle sporen en wissels op de baan. De baan is oorspronkelijk gebouwd met code 100 rails van Roco. Deze rails is echter niet meer verkrijgbaar en het aanbod tweedehands wordt ook steeds kleiner. Om de baan in de toekomst ook nog goed te kunnen blijven onderhouden is ervoor gekozen om alle rails te vervangen door Piko-A rails. Na het vervangen van de rails wordt ook direct de omliggende scenery onder handen genomen. Op deze manier hopen we over een aantal jaar een compleet gerenoveerde baan te hebben die weer jaren mee kan.</p>

