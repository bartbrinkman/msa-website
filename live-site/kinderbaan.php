			<h1>Kinderbaan</h1>
			
				<p>Al jaren is het binnen onze vereniging een traditie om ook voor jonge kinderen(vanaf 5-6 jaar) de interesse in model spoortreintjes levendig te houden .Ons Erelid Hans Buttner is een fenomeen in het bouwen van kleine emplacementjes , waar kinderen zelf mee kunnen spelen. Netjes stoppen op het station, letten op de seinen en de wissels, als ze het goed doen krijgen ze altijd een Machinisten diploma, de kinderen vinden het prachtig en genieten altijd met volle teugen. Vooral op beurzen is het leuk , de kinderen bij ons , spelend met de kinderbaan en de ouders, vaak ook opa,s en oma,s kunnen dan rustig verder de beurs bezoeken. Nu ons lid Hans dit , gezien zijn leeftijd, niet zelf meer deze kinderbanen kan bouwen en onderhouden, gaan wij dit nu zelf in ons clubhuis doen.</p>

				<p>Wij zijn heel blij met de schenking die Hans ons heeft gedaan, prachtige juweeltjes van kinderbanen, die wij piekfijn in orde gaan maken en waar wij een circus complex aan gaan toevoegen.</p>

				<p>In het voorjaar van 2016 zullen wij ook starten met het gaan bezoeken van scholen en instellingen voor gehandicapte kinderen, zodat ook zij kennis kunnen maken met deze mooie hobby.Wij hebben al enthousiaste reacties ontvangen, dank is ook verschuldigd aan onze sponsors die met een kleine financiële of materiële bijdrage dit mogelijkhebben gemaakt. Namens de vereniging en de kinderen hiervoor hartelijk dank.</p>

				<p>U hoort er wordt hard gewerkt om ook voor de kleintjes onder ons, de treinen onder de aandacht te brengen, wij houden u  verder via onze website op de hoogte van deze ontwikkelingen.</p>

				<p>In elk geval zal onze  nieuwe kinderbaan te zien zijn op de NMD dagen medio Maart 2016. Namens de MSA,  Michiel de Boer, en Peter Siebers.</p>
	
