			<h1>Marklinbaan</h1>
			<p>De baan bestaat uit drie rechthoekige rondlopende baan constructies welke allemaal aan de voorzijde tezamen  komen. Aan de voorzijde is ook het station, de huizenrijen en de vorige scenery geplaatst. Deze scenery is afkomstig van de verhuizing nadat wij van onze vorige locatie moesten verhuizen. Het geheel is dan ook vanaf het looppad goed te bekijken. Op de voorgrond van de Marklin-baan bevinden zich verschillende taferelen met beweegbare figuurtjes zoals fietsers, een rijschool en een complete autobaan met beweegbare auto's.  Meer verscholen opgesteld heeft elke rechthoekige baandeel een schaduwstation met elk een opstelcapaciteit van 3 a 4 treinen. Door slimme tussenverbindingen te leggen, is het mogelijk een veel grotere baan te cre&euml;ren met aanmerkelijk meer rijlengte dan de afzonderlijke baandelen. De Marklin-baan heeft eventueel ook nog een aansluiting met de Hoogoven-baan middels een niet permanente brugverbinding. Treinen kunnen dus van baan wisselen.</p>
			
			<p>De baan wordt bestuurd met een Marklin 6021 controller en de bijbehorende boosters met een rijvermogen van ca 160 VA. Alles is verder te regelen vanaf een schakelbord waarop de baanstructuur duidelijk zichtbaar is.</p>
			
