			<h1>Modelspoormerken</h1>
			<p>Er bestaan in de modelspoorwereld veel verschillende modelspoormerken. De bekendste zijn toch wel Marklin, Fleischmann en Roco. Andere merken zijn Piko, Lima, LS Models, KleiNSpoor, Mehano, Lilliput, Artitec, Rivarossi en natuurlijk Trix.</p>

			<p>Veel van deze merken leveren producten op verschillende schalen. De twee meest gebruikte schalen zijn H0 (Half nul, 1:87) en N (1:160). Het voordeel van de N schaal is dat er op minder ruimte een grotere rijlengte behaald kan worden, terwijl bij H0 meer gefocust kan worden op scenery. In schaal N krijgt de trein zijn stroom op &#233;&#233;n manier: Via de rails. De linkerspoorstaaf is de plus, de rechter de min. Bij H0 zijn hiervoor verschillende manieren.</p>

			<p>Modelspoorfabrikant Marklin gebruikt het 3-rail wisselstroom systeem. De treinen pikken hun stroom op door sleepcontacten onder aan de locomotief. Deze pikken de stroom op uit puntjes die in het midden van de rails zijn bevestigd. De stroom wordt door beide rails terug geleverd aan de transformator en de stroomkring is compleet. Ook Trix Express gebruikte vroeger 3-rail wisselstroom, maar dit merk is inmiddels niet meer verkrijgbaar. </p>

			<p>2-rail gelijkstroomsystemen (alle andere merken) werken hetzelfde als de N-schaal. De stroom gaat via &#233;&#233;n spoorstaaf naar de trein, terwijl hij door de andere terug gaat naar de transformator. Volgens velen is dit de beste manier omdat je geen lelijke puntcontacten in het midden van je rails hebt. </p>

			<p>Beide merken en typen hebben verschillende voor- en nadelen en het is aan de modelbouwer te kiezen welke hij het liefste gebruikt. </p>
