			<h1>N-baan</h1>
				<p>Ongeveer 4 jaar gelden is gestart met de invulling van het laatste nog vrije gedeelte van de treinenzolder:  de N-Baan in de schaal van 1:160 die op een spoorbreedte van 9 mm gebruik maakt van gelijkstroom.</p>

				<img src="images/N_spoorplan.png" alt="Sporenplan" />
				
				<p>Voor dit ca. 1, 70 x 6,00 m grote gedeelte is een klassiek baanontwerp gekozen, een zgn. dubbelsporige kruisingsvrije acht met een daar omheen gelegen enkelvoudig omloopspoor. In het "linkeroog" van de acht is een groot station met 5 sporen geprojecteerd tussen de stedelijke bebouwing van een kleine stad naar Duits voorbeeld. Het "rechteroog" van de acht krijgt een locdepot met ringloods voor de meerdere locomotieven en een rangeer-/opstelterrein. De coulissen die het N-project omgeven zijn een geschilderd landschap, eveneens naar Duits voorbeeld en laat niet alleen glooiende hellingen en bossen zien, maar ook een van de vakantie bekende steile rostswanden uit de Eifel.</p>
				
				<p>Om de sfeer van een "levend" gebied te simuleren, waarin niet alleen treinen rijden, worden voor verschillende punten van de baan bewegende onderwerpen bedacht en gemaakt. Ook wordt een dag en nacht ritme verbeeld door slim gebruik te maken van de tegenwoordig beschikbare led-verlichting gebruik te maken. Ook geluiden die in het echte leven altijd aanwezig zijn, variërend van onweersdonder tot het kraaien van de haan bij het ochtendgloren, doen de beleving van wat je als treinliefhebber ervaart realistisch overkomen. Overigens, de keuze voor het Duitse thema is voor de N-groep een hele praktisch en komt voort uit de beschikbaarheid van heel veel scenery naar Duits voorbeeld bij &#233;&#233;n van de leden van de N-groep.</p>
				
				<p>Omdat de N-baan relatief hoog boven de vloer van de zolder is gesitueerd en onderdelen slechts vanaf de voorzijde bereikbaar zijn, worden scenery groepen als inpasbare/verwijderbare modules gemaakt. Dit maakt het mogelijk om toekomstig onderhoud aan de baan en haar scenery uit te voeren zonder acrobatische touren op de baan en voorkomt ook dat onwillekeurig schade aan de baan optreedt.</p>

				<p>Het bouwen aan de N-baan is nog in volle gang. Als de aanleg van het railplan geheel is afgerond en voldoet aan de betrouwbaarheidseisen die de groep stelt aan de ongestoorde elektrische voeding van de baan kan worden gestart met de besturing van de treinenloop op de baan.</p>

				<p>Net als bij de ander banen zal gereden gaan worden met de "eigen" locs en wagons van de leden van de groep. Een deel van de groepsleden rijdt op zijn thuisbaan met digitale locomotieven. Een ander daarentegen doet dit met analoge locomotieven. Daarom is gekozen voor een besturingssysteem waarmee gelijktijdig zowel met analoge, als met digitale locs op de baan gereden kan worden. Het computerprogramma "Koploper" tezamen met de elektronica van "Dinamo" maakt dit mogelijk.De eerstkomende tijd zal het accent van de werkzaamheden van de groep zich vooral richten op het zich eigen maken van de theorie van de samenwerking tussen "Koploper en Dinamo".</p>
				
